def md_table(df, cols, headers=None, fmt=None):
    headers = headers or cols
    fmt = fmt or {}
    lines = ["| " + " | ".join(headers) + " |",
             "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        vals = []
        for c in cols:
            v = r[c]
            if c in fmt:
                v = format(v, fmt[c])
            elif isinstance(v, float):
                v = f"{v:.1f}"
            vals.append(str(v).replace("|", "、"))
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines)


